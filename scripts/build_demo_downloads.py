"""Build public-only offline presentation artifacts. No app imports or secrets.

Run after editing presentation files: python scripts/build_demo_downloads.py
Use --check in CI to detect stale artifacts without writing anything.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import io
import json
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
# Explicit allowlist: never archive a repository, credentials, or runtime data.
PUBLIC_FILES = (
    "index.html", "demo.html", "showcase.css", "demo.js", "demo-offline.js",
    "icon.svg", "privacy.html", "support.html", "style.css", "theme.js",
    "gym-flyer.html", "gym-qr.svg",
)
OFFLINE_FILE = "downloads/harnesssync-demo-offline.html"
ARCHIVE_FILE = "downloads/harnesssync-preview.zip"
SITE = "https://milesjo-cloud-project.github.io/HarnessSync/"


def standalone_demo(files: dict[str, bytes]) -> bytes:
    html = files["demo.html"].decode("utf-8")
    html = html.replace('<link rel="stylesheet" href="showcase.css">',
                        "<style>\n" + files["showcase.css"].decode("utf-8") + "</style>")
    html = html.replace('<script src="demo.js" defer></script>',
                        "<script>\n" + files["demo.js"].decode("utf-8") + "</script>")
    # The inline script must run after the markup exists, unlike a deferred file.
    start = html.index("<script>\n")
    end = html.index("</script>", start) + len("</script>")
    script = html[start:end]
    html = html[:start] + html[end:]
    html = html.replace("</body>", script + "\n</body>")
    html = html.replace('<script src="demo-offline.js" defer></script>', "")
    icon = base64.b64encode(files["icon.svg"]).decode("ascii")
    html = html.replace('href="icon.svg"', f'href="data:image/svg+xml;base64,{icon}"')
    html = html.replace("For an offline presentation, download the single-file demo below. The full app needs internet.",
                        "This single-file demo works offline. Entries reset on reload. Links to the website and full app need internet.")
    for target, label in [(OFFLINE_FILE, "Download offline demo ↓"),
                          (ARCHIVE_FILE, "Download site &amp; demo ZIP ↓")]:
        html = html.replace(f'<a class="text-link" href="{target}" download>{label}</a>', "")
    for page in ("index.html", "privacy.html", "support.html"):
        html = html.replace(f'href="{page}"', f'href="{SITE}{page}"')
    return ("\n".join(line.rstrip() for line in html.splitlines()) + "\n").encode("utf-8")


def service_worker(files: dict[str, bytes]) -> bytes:
    digest = hashlib.sha256()
    for name, content in sorted(files.items()):
        digest.update(name.encode("utf-8") + b"\0" + content)
    version = digest.hexdigest()[:16]
    assets = json.dumps(list(files), indent=2)
    return f'''// Generated by scripts/build_demo_downloads.py; public presentation files only.
"use strict";
const PREFIX = "harnesssync-presentation-";
const CACHE = PREFIX + "{version}";
const ASSETS = {assets};
const base = new URL("./", self.location.href);
const urls = ASSETS.map(path => new URL(path, base).href);
const allowed = new Set(urls);
self.addEventListener("install", event => {{
  event.waitUntil((async () => {{
    const cache = await caches.open(CACHE);
    // Bypass an older HTTP cache when installing a new asset version.
    await cache.addAll(urls.map(url => new Request(url, {{cache: "reload"}})));
    await self.skipWaiting();
  }})());
}});
self.addEventListener("activate", event => {{
  event.waitUntil((async () => {{
    for (const name of await caches.keys()) {{
      if (name.startsWith(PREFIX) && name !== CACHE) await caches.delete(name);
    }}
    await self.clients.claim();
  }})());
}});
self.addEventListener("fetch", event => {{
  const url = new URL(event.request.url);
  if (event.request.method !== "GET" || url.search) return;
  if (url.href === base.href) url.pathname += "index.html";
  if (!allowed.has(url.href)) return;
  event.respondWith((async () => {{
    const cache = await caches.open(CACHE);
    return (await cache.match(url.href)) || fetch(event.request);
  }})());
}});
self.addEventListener("message", event => {{
  if (event.data?.type !== "harnesssync-demo-check" || !event.ports[0]) return;
  event.waitUntil((async () => {{
    const cache = await caches.open(CACHE);
    const present = await Promise.all(urls.map(url => cache.match(url)));
    event.ports[0].postMessage({{type: "harnesssync-demo-ready", ready: present.every(Boolean)}});
  }})());
}});
'''.encode("utf-8")


def build_outputs() -> dict[str, bytes]:
    files = {name: (DOCS / name).read_bytes().replace(b"\r\n", b"\n") for name in PUBLIC_FILES}
    files[OFFLINE_FILE] = standalone_demo(files)
    worker = service_worker(files)
    archive = io.BytesIO()
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as bundle:
        for name, content in {**files, "demo-sw.js": worker, "START-HERE.txt": (
            "HarnessSync owner preview — fictional data only\n\n"
            "Unzip the entire folder, then open index.html in a desktop browser for the site.\n"
            "Open demo.html to try the demo, or downloads/harnesssync-demo-offline.html\n"
            "for a single file you can copy separately. No installation or server is needed.\n"
            "Phones may preview HTML attachments without running JavaScript; use a desktop\n"
            "browser for the downloaded files, or the hosted demo for phone presentations.\n"
            "Logging, projects, notes, history, and charts work without internet.\n"
            "Entries reset on reload. The full app and other external links need internet.\n"
        ).encode("utf-8")}.items():
            info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            bundle.writestr(info, content)
    return {OFFLINE_FILE: files[OFFLINE_FILE], "demo-sw.js": worker, ARCHIVE_FILE: archive.getvalue()}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for name, content in build_outputs().items():
        path = DOCS / name
        if args.check:
            existing = path.read_bytes() if path.exists() else b""
            if path.suffix != ".zip":
                existing = existing.replace(b"\r\n", b"\n")
            if existing != content:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
            print(f"Built {path.relative_to(ROOT)}")
    if stale:
        parser.exit(1, "Stale demo artifacts: " + ", ".join(stale) + "\nRun python scripts/build_demo_downloads.py\n")


if __name__ == "__main__":
    main()
