"""Package public translation catalogs for offline use. No private data."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
catalogs = {p.stem: {k.casefold(): v for k, v in json.loads(p.read_text(encoding="utf-8")).items()}
            for p in (root / "harnesssync/locales").glob("*.json")}
output = root / "harnesssync/offline_web/locales.js"
output.write_text("/* Generated by scripts/build_offline_locales.py. */\nconst hsCatalogs = "
                  + json.dumps(catalogs, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
